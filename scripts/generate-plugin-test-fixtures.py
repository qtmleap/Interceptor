#!/usr/bin/env python3
"""Regenerate immutable schema2 test packages with the real pinned SDK compiler, once."""
import argparse
import base64
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'fixtures/plugin-repository'

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def write_swift(ui_package, live):
    ui = ui_package['sourceFiles']
    primary = 'hooks/example.com/synthetic/POST.js'
    secondary = 'hooks/example.com/other/GET.js'
    lines = ['/// Generated by scripts/generate-plugin-test-fixtures.py; do not hand edit.', 'public enum PluginRepositorySources {']
    for label, value in [('primaryFile', primary), ('secondaryFile', secondary)]:
        lines.append('    static let ' + label + ' = ' + json.dumps(value))
    for label, source in [('primarySource', ui[primary]), ('secondarySource', ui[secondary])]:
        assert source.isascii() and source.endswith('\n') and '\\' not in source and '"""' not in source
        lines.append('    static let ' + label + ' = [')
        lines.extend('        ' + json.dumps(line) + ',' for line in source.split('\n'))
        lines.append('    ].joined(separator: "\\n")')
    lines.append('}')
    (ROOT / 'InterceptorUITests/PluginRepositorySources.swift').write_text('\n'.join(lines) + '\n')
    encoded = base64.b64encode(live).decode()
    chunks = '\n'.join('        ' + encoded[index:index + 80] for index in range(0, len(encoded), 80))
    swift = ('// Generated by scripts/generate-plugin-test-fixtures.py; exact SDK-emitted package bytes.\n'
             'import Foundation\n\npublic enum SDKFilesystemHookFixture {\n'
             '    static let sha256 = "' + hashlib.sha256(live).hexdigest() + '"\n'
             '    static let package = Data(\n        base64Encoded: """\n' + chunks
             + '\n        """,\n        options: .ignoreUnknownCharacters,\n    )\n}\n')
    (ROOT / 'InterceptorTests/SDKFilesystemHookFixture.swift').write_text(swift)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk-root', type=Path, required=True)
    options = parser.parse_args()
    sdk = options.sdk_root.resolve(strict=True)
    version = subprocess.check_output(['bun', '--version'], text=True).strip()
    if version != (sdk / '.bun-version').read_text().strip():
        raise SystemExit('Use the SDK-pinned Bun runtime')
    with tempfile.TemporaryDirectory(prefix='interceptor-native-fixtures-') as temporary:
        work = Path(temporary)
        shutil.copytree(FIXTURES / 'authored/plugins', work / 'plugins')
        (work / 'types').mkdir()
        shutil.copy2(sdk / 'types/interceptor.d.ts', work / 'types/interceptor.d.ts')
        result = subprocess.run(['bun', str(sdk / 'tools/compile.mjs'), str(work)],
                                capture_output=True, text=True, env=dict(os.environ, INTERCEPTOR_PYTHON=os.sys.executable))
        if result.returncode:
            raise SystemExit(result.stderr.strip())
        emitted = json.loads(result.stdout)
    spec = importlib.util.spec_from_file_location('native_fixture_sdk', sdk / 'tools/repository_config.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    outputs = {}
    for name, filename in [('ui-multifile', 'multi-file-hooks.json'), ('live-multifile', 'sdk-live-multi-file-hooks.json')]:
        package = emitted[name]
        module.validate_manifest(package['manifest'], name)
        raw = module.package_bytes(package['manifest'], package['sourceFiles'])
        (FIXTURES / filename).write_bytes(raw)
        outputs[filename] = {'sha256': hashlib.sha256(raw).hexdigest(), 'size': len(raw)}
    write_swift(emitted['ui-multifile'], (FIXTURES / 'sdk-live-multi-file-hooks.json').read_bytes())
    tool_paths = ['.bun-version', 'bun.lock', 'package.json', 'tools/compile.mjs', 'tools/discover_routes.py',
                  'tools/route_sources.py', 'tools/repository_config.py', 'types/interceptor.d.ts']
    provenance = {'schemaVersion': 1, 'sdkRepository': 'https://github.com/qtmleap/Interceptor-Plugins',
                  'sdkRevision': subprocess.check_output(['git', '-C', str(sdk), 'rev-parse', 'HEAD'], text=True).strip(),
                  'bunVersion': version, 'compilerEntryPoint': 'tools/compile.mjs',
                  'command': 'python3 scripts/generate-plugin-test-fixtures.py --sdk-root /path/to/Interceptor-Plugins',
                  'sdkInputs': {name: sha(sdk / name) for name in tool_paths},
                  'authoredInputs': {str(p.relative_to(FIXTURES)): sha(p) for p in sorted((FIXTURES / 'authored').rglob('*')) if p.is_file()},
                  'packages': outputs}
    (FIXTURES / 'provenance.json').write_text(json.dumps(provenance, indent=2, sort_keys=True) + '\n')
    print(json.dumps(outputs, indent=2))

if __name__ == '__main__':
    main()
