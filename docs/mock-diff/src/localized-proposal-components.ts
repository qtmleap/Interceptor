export function localizedProposalComponents(lang: 'ja' | 'en') {
  const t = (text: string) => {
    if (lang === 'ja') return text;
    const translated = english[text];
    if (translated !== undefined) return translated;
    if (/[\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Han}]/u.test(text)) {
      throw new Error(`Missing English proposal translation: ${text}`);
    }
    return text;
  };
  return {
    note: lang === 'en'
      ? 'Component proposals based on the existing native screens. The implementation uses OS-standard controls.'
      : '既存のネイティブ画面を基にした部品案です。実装ではOS標準の表示を使用します。',
    row: (label: string, value = '', detail = false, sub = '') => components.row(t(label), t(value), detail, t(sub)),
    section: (title: string, content: string, footer: string | string[] = '') => components.section(t(title), content,
      Array.isArray(footer) ? footer.map(t).join('\n') : t(footer)),
    badge: (kind: Parameters<typeof components.badge>[0], label: string) => components.badge(kind, t(label)),
    choice: (title: string, selected = false) => components.choice(t(title), selected),
    notice: (kind: Parameters<typeof components.notice>[0], title: string) => components.notice(kind, t(title)),
    historyItem: (kind: Parameters<typeof components.historyItem>[0], title: string, time: string, description: string) => components.historyItem(kind, t(title), t(time), t(description)),
    toggle: (title: string, checked = false, disabled = false) => components.toggle(t(title), checked, disabled),
    page: (title: string, content: string, options: Parameters<typeof components.page>[2] = {}) => components.page(t(title), content, {
      ...options, back: options.back === undefined ? undefined : t(options.back),
      action: options.action === undefined ? undefined : t(options.action), lang,
    }),
  };
}
